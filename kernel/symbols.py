#!/usr/bin/env python3
"""Regenerate src/symbols.tsv: TeX command name, text, math class.

Names and characters come from unicode-math's table, the classic names
LaTeX, amsmath and amssymb declare (\\le, \\to, \\lvert), the upright Greek letters
under their classic names, and UniTeX's aliases. A classic name unicode-math
lacks takes the character the reference renderer, utftex, shows for it.
Run from this directory with TeX Live and utftex installed.
"""
import json
from pathlib import Path
import re
import subprocess
import unicodedata


def tex(name):
    return Path(subprocess.check_output(["kpsewhich", name], text=True).strip()).read_text()


table = {m[2]: (chr(int(m[1], 16)), m[3]) for m in re.finditer(
    r'\\UnicodeMathSymbol\{"([0-9A-F]+)\}\{\\(\w+)\s*\}\{\\(\w+)\}', tex("unicode-math-table.tex"))}
entries = dict(table)
for name, value in table.items():
    if name.startswith("mup") and value[1] == "mathalpha":
        entries.setdefault(name[3:], value)  # \mupalpha is \alpha

classic = set()
for source in ("fontmath.ltx", "latex.ltx", "amssymb.sty", "amsmath.sty"):
    classic.update(re.findall(
        r"[\\@](?:DeclareMath(?:Symbol|Delimiter|Accent|Radical)|let|def|DeclareRobustCommand|newcommand)"
        r"\s*\{?\s*\\([A-Za-z]+)", tex(source)))
# Names the prelude's own definitions use.
classic.update(re.findall(r"\\([A-Za-z]+)", (Path(__file__).parent / "src/prelude.tex").read_text()))


def shown(name):
    result = subprocess.run(["utftex", "-F", "text", "\\" + name], capture_output=True)
    rows = [row for row in result.stdout.decode("utf-8", "replace").split("\n") if row.strip()]
    if result.returncode == 0 and len(rows) == 1 and "ERROR" not in rows[0]:
        return rows[0].strip()
    return None


for name in sorted(classic - set(entries)):
    value = shown(name)
    if value and len(value) == 1:
        entries[name] = (value, table.get(name, ("", ""))[1])
aliases = json.loads((Path(__file__).parent / "../vendor/unitex-symbols.json").read_text())["symbols"]
for name, value in aliases.items():
    entries.setdefault(name, (value, ""))

# NFC, so no canonical singleton such as U+212B ANGSTROM SIGN (UTR #25).
lines = ["\t".join((name, unicodedata.normalize("NFC", text), kind.removeprefix("math"))) for name, (text, kind) in sorted(entries.items())]
(Path(__file__).parent / "src/symbols.tsv").write_text(
    "# name\ttext\tclass; generated by symbols.py from unicode-math (LPPL) and UniTeX (MIT)\n"
    + "\n".join(lines) + "\n")
print(len(lines), "symbols")
